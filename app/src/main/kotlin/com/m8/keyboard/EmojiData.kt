import android.graphics.Paint

/** One named group on the emoji page: a title and the things in it (shown as one sideways-scrolling row). */
class EmojiSection(val title: String, val items: List<String>, val isText: Boolean)

/**
 * What the emoji page offers, in sections you scroll through up and down: emoji first, then
 * old-school text smileys and kaomoji. Anything this phone's font cannot draw is left out of the
