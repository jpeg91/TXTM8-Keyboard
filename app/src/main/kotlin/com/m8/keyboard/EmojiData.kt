    val sections: List<EmojiSection> by lazy {
        val paint = Paint()
        val result = ArrayList<EmojiSection>()
        for ((title, raw) in EMOJI) {
            val items = raw.trim().split(Regex("\\s+")).filter { it.isNotEmpty() && paint.hasGlyph(it) }.distinct()
            if (items.isNotEmpty()) result.add(EmojiSection(title, items, isText = false))
        }
        for ((title, items) in TEXT) result.add(EmojiSection(title, items, isText = true))
        result
    }

